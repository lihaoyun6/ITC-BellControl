/* ══ boot ═══════════════════════════════════════════════════════════ */
(function boot(){
  const saved = savedSession();          /* 本机留着没过期的令牌吗（见 10-data.js） */
  if (!saved){ forgetLogin(); renderAll(); return; }   /* 没有 / 已过期 → 停在登录页 */
  /* **先把界面画成主界面，再去问服务器。** 这一笔就是「不闪登录页」的全部：
     先画登录页、等结果回来再换成主界面，人就会看见登录页闪一下 —— 而答案其实
     早在开局就知道了（savedSession() 是同步的），没理由先画错的再改。
     这趟往返期间顶栏写着「连接中」、主区写着「正在连接广播服务器」，都是实话。

     代价：令牌真被服务器否掉、而本机又没留用户名密码时（没勾「记住登录状态」），
     会反过来闪一下主界面外壳再落到登录页。那时人本来就得重登，比每次刷新都闪
     登录页划算。本机留着用户名密码的话连这一下都没有 —— 探针吃 401 会自己续一张
     令牌重发一次（见 10-data.js 的 reLogin），人就停在主界面上。 */
  S.token = saved;
  S.conn = "busy";
  S.view = "app";
  /* 停在刷新前那个页签（本机记着的 bc.lastMode，见 30-view-list.js）——**在第一帧之前**
     就定下来：晚一步（等数据回来再切）人先看到的是一整页铃声计划加一句「正在连接广播
     服务器」，然后才跳到他原来那一页。页签从第一帧起就是对的，之后只是内容填进来。
     只在进得了主界面这一支这么做；上面那支停在登录页，重登之后该从铃声计划起步，
     而不是把上一趟的视图捡回来（那个记忆跟着会话走，forgetLogin() 会抹掉）。

     这条路要成立，靠的是另外三处各让一步（2026-10-16 实测踩过一遍，别再往回改）：
       · loadAll() 尾巴那个 selectGroup() 不许再按 S.mode —— 一按就冲掉了刚恢复的页签
         （「回到列表视图」那句话搬去了侧栏的点击处理里，那才是它的意思）；
       · renderExam() 得自己兜住 S.exam 是 null 的那一帧（loadAll() 之前它还没认配置，
         不兜的话第一帧就抛错，整条启动链子断在这儿）；
       · renderTasks() 在「还没连上」时那句空表话得换成「正在连接…」，不然是句假话。
     定时任务那一页的数据不用管：下面 loadAll() 里有它，回来自己会补画。 */
  /* 记忆里的页签要**还在**才恢复：从明文 http 打开时「实时对讲」这一页根本
     摆不出来（拿不到麦克风，见 75-view-live.js 的 liveUsable），恢复它等于
     把人送进一个没有任何入口的页面 —— 顶栏和导航栏里都找不到那个页签，
     退不出来。所以这会儿落到「铃声计划」上。「在线播放」这一条只在**连 Web Audio
     都没有**的浏览器上才会命中 —— 明文 http 下它退到 ScriptProcessorNode 照样能放
     （见 75-view-live.js 的 playUsable），页签也是摆着的。

     **「定时任务」也落到铃声计划上**（用户定的：它不参与刷新恢复）。它现在不是
     页签了 —— 入口只有侧栏底部那张卡片，而那张卡片只在铃声计划这一页里；刷新
     直接停在它上面，人看到的是一个没有页签可点的页面。本机那份记忆里可能还留着
     老版本写下的 "tasks"（goMode 那边从这一版起不再记它了），所以这一句不能省。 */
  S.mode = (lastMode === "live" && !liveUsable()) ||
           (lastMode === "online" && !playUsable()) ||
           lastMode === "tasks" ? "list" : lastMode;
  renderAll();
  /* 拿存着的令牌去问一个**认令牌**的接口，通了就直接进主界面 —— 刷新不用重输密码
     就是这一趟办到的事。

     **别拿 /auth 当探针**：那是纯登录接口，只认 name + password，请求头上的令牌
     它看都不看（带 Bearer 前缀也一样）。以前这里问的就是 /auth，于是拿着有效令牌
     也必然吃「用户名不能为空」，还把令牌当场删掉 —— 「记住登录状态」等于摆设。
     实测见 30-view-list.js 里「探针为什么不是 /auth」那段。 */
  api("GET","/timing-bells-groups/all",{params:{withUser:"true"}})
    .then(()=>{ S.conn = "ok"; return loadAll(); })
    /* 这一支**不碰 S.mode**：第一帧就已经把页签摆对了，数据回来只是把页面上那句
       「正在连接…」换成真东西（顺带顶栏从「连接中」改成「已连接」）。 */
    .then(()=>{ renderAll(); openStatusFeed(); })
    .catch(()=>{ forgetLogin(); S.conn = "idle"; S.view = undefined; renderAll(); });
})();
